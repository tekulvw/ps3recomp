static int failures, checks;
#define CHECK(v, name) do { checks++; if (!(v)) { failures++; fprintf(stderr, "FAIL %s\n", name); } } while (0)

/* rsx_draw_engine.c's eng_depth_row_to_guest, D24S8 branch. */
static void cpu_z24(u8* dst, float d)
{
    d = d > 0.0f ? d : 0.0f;
    d = d < 1.0f ? d : 1.0f;
    const u32 v = (u32)((double)d * 16777215.0 + 0.5);
    dst[0] = (u8)(v >> 16); dst[1] = (u8)(v >> 8); dst[2] = (u8)v; dst[3] = 0;
}

/* ---- small helpers on the backend's own synchronous command buffer ---- */
static void put_bits(vk_buffer* dev, const uint32_t* bits, u32 n)
{
    vk_buffer st = {0};
    assert(vk_create_host_buffer(&st, (VkDeviceSize)n * 4u, VK_BUFFER_USAGE_TRANSFER_SRC_BIT) == 0 && st.coherent);
    memcpy(st.ptr, bits, (size_t)n * 4u);
    assert(vk_begin() == 0);
    VkBufferCopy c = { 0, 0, (VkDeviceSize)n * 4u };
    pvkCmdCopyBuffer(s_vk.cmd, st.buf, dev->buf, 1, &c);
    assert(vk_sync() == 0);
    vk_destroy_buffer(&st);
}
/* The conversion alone, over arbitrary bits (a depth copy may clamp them). */
static void convert_bits(vk_buffer* dev, const uint32_t* bits, u8* got, u32 w, u32 h)
{
    put_bits(dev, bits, w * h);
    vk_buffer out = {0};
    assert(vk_create_host_buffer(&out, (VkDeviceSize)w * h * 4u, VK_BUFFER_USAGE_TRANSFER_DST_BIT) == 0);
    assert(vk_begin() == 0);
    vk_e5_record_words(s_vk.cmd, s_e5.sync_set, dev->buf, w, h, VK_PIPELINE_STAGE_TRANSFER_BIT, VK_ACCESS_TRANSFER_READ_BIT);
    VkBufferCopy c = { 0, 0, (VkDeviceSize)w * h * 4u };
    pvkCmdCopyBuffer(s_vk.cmd, dev->buf, out.buf, 1, &c);
    VkMemoryBarrier hb = { .sType = VK_STRUCTURE_TYPE_MEMORY_BARRIER, .srcAccessMask = VK_ACCESS_TRANSFER_WRITE_BIT,
                           .dstAccessMask = VK_ACCESS_HOST_READ_BIT };
    pvkCmdPipelineBarrier(s_vk.cmd, VK_PIPELINE_STAGE_TRANSFER_BIT, VK_PIPELINE_STAGE_HOST_BIT, 0, 1, &hb, 0, NULL, 0, NULL);
    assert(vk_sync() == 0);
    vk_invalidate(&out);
    memcpy(got, out.ptr, (size_t)w * h * 4u);
    vk_destroy_buffer(&out);
}
/* In-range floats straight into a depth target's depth aspect. */
static void fill_depth(u32 depth, const float* v, u32 w, u32 h)
{
    vk_buffer st = {0};
    assert(vk_create_host_buffer(&st, (VkDeviceSize)w * h * 4u, VK_BUFFER_USAGE_TRANSFER_SRC_BIT) == 0 && st.coherent);
    memcpy(st.ptr, v, (size_t)w * h * 4u);
    assert(vk_begin() == 0);
    vk_cmd_after_everything(s_vk.cmd);
    VkBufferImageCopy r = { .imageSubresource = { VK_IMAGE_ASPECT_DEPTH_BIT, 0, 0, 1 }, .imageExtent = { w, h, 1 } };
    pvkCmdCopyBufferToImage(s_vk.cmd, st.buf, s_eobj[depth].im.img, VK_IMAGE_LAYOUT_GENERAL, 1, &r);
    vk_cmd_after_everything(s_vk.cmd);
    assert(vk_sync() == 0);
    vk_destroy_buffer(&st);
}

/* texelFetch of a sampled engine texture (its view's component mapping
 * applies) into floats, through a tiny compute pipeline of the test's own. */
static struct { VkDescriptorSetLayout sl; VkPipelineLayout pl; VkShaderModule m; VkPipeline p;
                VkDescriptorPool dp; VkSampler s; } F;
static void fetch_init(void)
{
    VkDescriptorSetLayoutBinding b[2] = {
        { 0, VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER, 1, VK_SHADER_STAGE_COMPUTE_BIT, NULL },
        { 1, VK_DESCRIPTOR_TYPE_STORAGE_BUFFER, 1, VK_SHADER_STAGE_COMPUTE_BIT, NULL } };
    VkDescriptorSetLayoutCreateInfo lci = { .sType = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_CREATE_INFO,
                                            .bindingCount = 2, .pBindings = b };
    assert(pvkCreateDescriptorSetLayout(s_vk.device, &lci, NULL, &F.sl) == VK_SUCCESS);
    VkPushConstantRange pcr = { VK_SHADER_STAGE_COMPUTE_BIT, 0, 8 };
    VkPipelineLayoutCreateInfo plci = { .sType = VK_STRUCTURE_TYPE_PIPELINE_LAYOUT_CREATE_INFO, .setLayoutCount = 1,
                                        .pSetLayouts = &F.sl, .pushConstantRangeCount = 1, .pPushConstantRanges = &pcr };
    assert(pvkCreatePipelineLayout(s_vk.device, &plci, NULL, &F.pl) == VK_SUCCESS);
    assert(vk_create_shader(vk_fetch_comp_spv, sizeof vk_fetch_comp_spv, &F.m) == 0);
    VkComputePipelineCreateInfo cci = { .sType = VK_STRUCTURE_TYPE_COMPUTE_PIPELINE_CREATE_INFO,
        .stage = { .sType = VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO, .stage = VK_SHADER_STAGE_COMPUTE_BIT,
                   .module = F.m, .pName = "main" }, .layout = F.pl };
    assert(pvkCreateComputePipelines(s_vk.device, VK_NULL_HANDLE, 1, &cci, NULL, &F.p) == VK_SUCCESS);
    VkDescriptorPoolSize ps[2] = { { VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER, 256 }, { VK_DESCRIPTOR_TYPE_STORAGE_BUFFER, 256 } };
    VkDescriptorPoolCreateInfo dci = { .sType = VK_STRUCTURE_TYPE_DESCRIPTOR_POOL_CREATE_INFO, .maxSets = 256,
                                       .poolSizeCount = 2, .pPoolSizes = ps };
    assert(pvkCreateDescriptorPool(s_vk.device, &dci, NULL, &F.dp) == VK_SUCCESS);
    VkSamplerCreateInfo sci = { .sType = VK_STRUCTURE_TYPE_SAMPLER_CREATE_INFO, .magFilter = VK_FILTER_NEAREST,
                                .minFilter = VK_FILTER_NEAREST, .mipmapMode = VK_SAMPLER_MIPMAP_MODE_NEAREST,
                                .addressModeU = VK_SAMPLER_ADDRESS_MODE_CLAMP_TO_EDGE,
                                .addressModeV = VK_SAMPLER_ADDRESS_MODE_CLAMP_TO_EDGE,
                                .addressModeW = VK_SAMPLER_ADDRESS_MODE_CLAMP_TO_EDGE };
    assert(pvkCreateSampler(s_vk.device, &sci, NULL, &F.s) == VK_SUCCESS);
}
static void fetch_shutdown(void)
{
    pvkDestroySampler(s_vk.device, F.s, NULL); pvkDestroyDescriptorPool(s_vk.device, F.dp, NULL);
    pvkDestroyPipeline(s_vk.device, F.p, NULL); pvkDestroyShaderModule(s_vk.device, F.m, NULL);
    pvkDestroyPipelineLayout(s_vk.device, F.pl, NULL); pvkDestroyDescriptorSetLayout(s_vk.device, F.sl, NULL);
}
static void fetch(u32 handle, u32 w, u32 h, float* out)
{
    assert(handle && s_eobj[handle].kind == VK_ENG_TEXTURE);
    vk_buffer ob = {0};
    assert(vk_create_host_buffer(&ob, (VkDeviceSize)w * h * 16u, VK_BUFFER_USAGE_STORAGE_BUFFER_BIT) == 0);
    VkDescriptorSet set;
    VkDescriptorSetAllocateInfo dai = { .sType = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_ALLOCATE_INFO, .descriptorPool = F.dp,
                                        .descriptorSetCount = 1, .pSetLayouts = &F.sl };
    assert(pvkAllocateDescriptorSets(s_vk.device, &dai, &set) == VK_SUCCESS);
    VkDescriptorImageInfo ii = { F.s, s_eobj[handle].im.view, VK_IMAGE_LAYOUT_GENERAL };
    VkDescriptorBufferInfo bi = { ob.buf, 0, VK_WHOLE_SIZE };
    VkWriteDescriptorSet wr[2] = {
        { .sType = VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET, .dstSet = set, .dstBinding = 0, .descriptorCount = 1,
          .descriptorType = VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER, .pImageInfo = &ii },
        { .sType = VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET, .dstSet = set, .dstBinding = 1, .descriptorCount = 1,
          .descriptorType = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER, .pBufferInfo = &bi } };
    pvkUpdateDescriptorSets(s_vk.device, 2, wr, 0, NULL);
    assert(vk_begin() == 0);
    vk_cmd_after_everything(s_vk.cmd);
    pvkCmdBindPipeline(s_vk.cmd, VK_PIPELINE_BIND_POINT_COMPUTE, F.p);
    pvkCmdBindDescriptorSets(s_vk.cmd, VK_PIPELINE_BIND_POINT_COMPUTE, F.pl, 0, 1, &set, 0, NULL);
    const u32 ext[2] = { w, h };
    pvkCmdPushConstants(s_vk.cmd, F.pl, VK_SHADER_STAGE_COMPUTE_BIT, 0, 8, ext);
    pvkCmdDispatch(s_vk.cmd, (w + 7) / 8, (h + 7) / 8, 1);
    VkMemoryBarrier hb = { .sType = VK_STRUCTURE_TYPE_MEMORY_BARRIER, .srcAccessMask = VK_ACCESS_SHADER_WRITE_BIT,
                           .dstAccessMask = VK_ACCESS_HOST_READ_BIT };
    pvkCmdPipelineBarrier(s_vk.cmd, VK_PIPELINE_STAGE_COMPUTE_SHADER_BIT, VK_PIPELINE_STAGE_HOST_BIT, 0, 1, &hb, 0, NULL, 0, NULL);
    assert(vk_sync() == 0);
    vk_invalidate(&ob);
    memcpy(out, ob.ptr, (size_t)w * h * 16u);
    vk_destroy_buffer(&ob);
}

enum { W = 2048, H = 1024 };

int main(int argc, char** argv)
{
    if (argc != 5) { fprintf(stderr, "usage: fixture MODE(on|off) REQUIRE_HARDWARE VENDOR_ID DEVICE_ID\n"); return 2; }
    const int gpu_z24 = !strcmp(argv[1], "on");
    const int hardware = atoi(argv[2]);
    const uint32_t vendor = (uint32_t)strtoul(argv[3], NULL, 0), device_id = (uint32_t)strtoul(argv[4], NULL, 0);
    setenv("PS3RECOMP_RSX_ENGINE", "dispatch", 1);
    setenv("PS3RECOMP_VK_WINDOW", "0", 1);
    setenv("PS3RECOMP_VK_GUEST_PROGRAMS", "0", 1);
    if (gpu_z24) setenv("PS3RECOMP_VK_GPU_Z24", "1", 1); else unsetenv("PS3RECOMP_VK_GPU_Z24");
    assert(rsx_vulkan_backend_init(8, 8, "depth z24 synthetic") == 0 && s_vk.eng_active);
    VkPhysicalDeviceProperties props; pvkGetPhysicalDeviceProperties(s_vk.phys, &props);
    if (hardware) {
        CHECK(props.vendorID == vendor && props.deviceID == device_id, "requested GPU");
        CHECK(props.deviceType == VK_PHYSICAL_DEVICE_TYPE_DISCRETE_GPU || props.deviceType == VK_PHYSICAL_DEVICE_TYPE_INTEGRATED_GPU,
              "hardware device");
    }
    const rsx_draw_backend* be = &s_vk_engine_backend;
    CHECK(be->depth_store_z24 && be->depth_z24_texture && be->depth_z24_view && be->submit_async &&
          be->completion_status && be->submit_and_wait_checked, "backend advertises E5");

    if (s_vk.depth_format != VK_FORMAT_D32_SFLOAT && s_vk.depth_format != VK_FORMAT_D32_SFLOAT_S8_UINT) {
        u32 z = vk_eng_depth_target_create(NULL, 4, 4); u8 g4[64];
        CHECK(vk_eng_depth_store_z24(NULL, z, 4, 4, g4, 16) != 0 && vk_eng_depth_z24_view(NULL, z, 4, 4, 0xAAE4u, 0xA5u) == 0,
              "non-D32 depth refused visibly");
        printf("%d checks, %d failures (depth format %d: conversion refused)\n", checks, failures, (int)s_vk.depth_format);
        rsx_vulkan_backend_shutdown();
        return failures ? 1 : 0;
    }

    /* ---- tickets ---- */
    {
        const u64 t1 = vk_eng_submit_async(NULL, RSX_BE_FLUSH_GUEST_REFERENCE);
        const u64 t2 = vk_eng_submit_async(NULL, RSX_BE_FLUSH_GUEST_REFERENCE);
        CHECK(t1 && t2 == t1 + 1, "tickets increase in submission order");
        CHECK(vk_eng_completion_status(NULL, t2, 1) == 1 && vk_eng_completion_status(NULL, t1, 0) == 1,
              "a waited ticket and every earlier one complete");
        CHECK(vk_eng_completion_status(NULL, t2 + 1, 0) == -1 && vk_eng_completion_status(NULL, 0, 0) == -1,
              "unissued tickets are not certificates");
        const u64 waits = s_e5.cap_waits;
        u64 last = 0;
        for (u32 i = 0; i < 3 * VK_E5_SLOTS; i++) last = vk_eng_submit_async(NULL, RSX_BE_FLUSH_GUEST_REFERENCE);
        CHECK(last && !vk_e5_failed() && s_e5.count <= VK_E5_SLOTS, "more tickets than slots stay healthy");
        printf("ring: %llu tickets, %llu cap waits while issuing %u\n", (unsigned long long)s_e5.issued,
               (unsigned long long)(s_e5.cap_waits - waits), 3 * VK_E5_SLOTS);
        CHECK(vk_eng_submit_and_wait_checked(NULL, RSX_BE_FLUSH_GUEST_REFERENCE) == 1, "checked flush certifies");
        CHECK(vk_eng_completion_status(NULL, last, 0) == 1, "checked flush completes earlier tickets");
    }

    u32 depth = vk_eng_depth_target_create(NULL, W, H);
    CHECK(depth != 0, "depth target");
    uint32_t* bits = malloc((size_t)W * H * 4u); u8* got = malloc((size_t)W * H * 4u);
    assert(bits && got && depth);
    if (!gpu_z24) {
        u8 g[16];
        CHECK(vk_eng_depth_store_z24(NULL, depth, 2, 2, g, 8) == -1 && vk_eng_depth_z24_texture(NULL, 2, 2, 0xAAE4u, 0xA5u) == 0,
              "without PS3RECOMP_VK_GPU_Z24 the store and alias decline (engine keeps its CPU path)");
        CHECK(vk_e5_pipeline() == 0, "conversion pipeline");
        const u32 v = vk_eng_depth_z24_view(NULL, depth, 16, 16, 0xAAE4u, 0xA5u);
        CHECK(v != 0, "the GPU view does not depend on PS3RECOMP_VK_GPU_Z24");
        if (v) vk_eng_release(NULL, v);
        vk_eng_release(NULL, depth);
        free(bits); free(got);
        printf("%d checks, %d failures (mode off)\n", checks, failures);
        rsx_vulkan_backend_shutdown();
        return failures ? 1 : 0;
    }

    /* ---- the conversion over raw bit patterns ---- */
    CHECK(vk_e5_pipeline() == 0, "conversion pipeline");
    vk_buffer dev = {0};
    assert(vk_e5_device_buffer(&dev, (VkDeviceSize)W * H * 4u) == 0);
    unsigned long long mismatch = 0, tested = 0;
    {
        static const uint32_t special[] = {
            0x00000000u, 0x80000000u, 0x00000001u, 0x007FFFFFu, 0x00800000u, 0x3F800000u,
            0x3F7FFFFFu, 0x3F800001u, 0x7F800000u, 0xFF800000u, 0x7FC00000u, 0xFFC00000u,
            0x7F800001u, 0xBF800000u, 0x33800000u, 0x33000000u, 0x337FFFFFu, 0x33800001u,
            0x40000000u, 0x7F7FFFFFu, 0x34000000u, 0x2F800000u };
        u32 n = 0;
        for (u32 i = 0; i < sizeof special / sizeof special[0]; i++) bits[n++] = special[i];
        for (u32 k = 0; n + 9 <= (u32)W * H && k < 16777216u; k += 4099u) {
            float c = (float)((k + 0.5) / 16777215.0); uint32_t cb; memcpy(&cb, &c, 4);
            for (int d = -4; d <= 4; d++) bits[n++] = cb + (uint32_t)d;
        }
        while (n < (u32)W * H) { bits[n] = (uint32_t)n * 2654435761u; n++; }
        const int exhaustive = getenv("DEPTH_Z24_EXHAUSTIVE") != NULL;
        const uint32_t step = exhaustive ? 1u : 257u;
        uint64_t base = 0;
        for (int pass = 0; ; pass++) {
            u32 m = (u32)W * H;
            if (pass) {
                if (base > 0x3F800000u) break;
                m = 0;
                for (; m < (u32)W * H && base <= 0x3F800000u; m++, base += step) bits[m] = (uint32_t)base;
                for (u32 i = m; i < (u32)W * H; i++) bits[i] = 0;
            }
            convert_bits(&dev, bits, got, W, H);
            for (u32 i = 0; i < m; i++) {
                float f; memcpy(&f, &bits[i], 4);
                u8 want[4]; cpu_z24(want, f);
                if ((bits[i] & 0x7FC00000u) == 0x7F800000u && (bits[i] & 0x003FFFFFu)) memset(want, 0, 4);
                if (memcmp(want, got + 4u * i, 4) && mismatch++ < 8)
                    fprintf(stderr, "mismatch bits %08X: cpu %02X%02X%02X%02X gpu %02X%02X%02X%02X\n", bits[i],
                            want[0], want[1], want[2], want[3], got[4*i], got[4*i+1], got[4*i+2], got[4*i+3]);
            }
            tested += pass ? m : 0;
        }
        printf("compared %llu bit patterns in [0, 1]%s plus %u specials/boundaries/arbitrary\n", tested,
               exhaustive ? " (all)" : "", (u32)W * H);
        CHECK(mismatch == 0, "GPU z24 conversion equals the CPU conversion bit for bit");
    }
    vk_destroy_buffer(&dev);

    /* ---- the store through a real depth target ---- */
    u32 small = vk_eng_depth_target_create(NULL, 8, 4); CHECK(small != 0, "small depth target");
    vk_eng_clear_depth_stencil(NULL, small, RSX_BE_CLEAR_DEPTH | RSX_BE_CLEAR_STENCIL, 0.25f, 0);
    {
        u8 padded[4 * 40]; memset(padded, 0xEE, sizeof padded);
        CHECK(vk_eng_depth_store_z24(NULL, small, 5, 3, padded, 40) == 0, "store after a recorded clear");
        u8 want[4]; cpu_z24(want, 0.25f); int ok = 1;
        for (u32 y = 0; y < 4; y++) for (u32 x = 0; x < 10; x++) {
            const u8* p = padded + y * 40 + x * 4;
            if (y < 3 && x < 5) ok &= !memcmp(p, want, 4);
            else ok &= p[0] == 0xEE && p[1] == 0xEE && p[2] == 0xEE && p[3] == 0xEE;
        }
        CHECK(ok, "recorded clear visible; padding and rows outside the rectangle untouched");
    }
    {
        enum { SW = 40, SH = 11 };
        float* fv = malloc(SW * SH * 4);
        for (u32 i = 0; i < SW * SH; i++) fv[i] = (float)((i * 2654435761u) & 0xFFFFFF) / 16777215.0f;
        fv[0] = 0.0f; fv[1] = 1.0f; fv[2] = 0.5f;
        u32 big = vk_eng_depth_target_create(NULL, SW, SH);
        fill_depth(big, fv, SW, SH);
        float rb[SW * SH]; u8 via_cpu[SW * SH * 4], via_gpu[SW * SH * 4];
        CHECK(vk_eng_depth_readback(NULL, big, 0, 0, SW, SH, rb, SW * 4) == 0, "float readback");
        for (u32 i = 0; i < SW * SH; i++) cpu_z24(via_cpu + 4 * i, rb[i]);
        CHECK(vk_eng_depth_store_z24(NULL, big, SW, SH, via_gpu, SW * 4) == 0, "tight store");
        CHECK(!memcmp(via_cpu, via_gpu, sizeof via_cpu), "store equals readback + CPU conversion");

        /* Alias and view texels against the decoded upload of the stored bytes. */
        fetch_init();
        enum { AW = 37, AH = 9 };
        static const u32 remaps[] = { 0xAAE4u, 0xAA93u, 0xAA1Bu, 0x55E4u, 0xAAD8u, 0x0000u, 0xFF39u, 0xAA4Eu };
        static const u32 fmts[] = { 0xA5u, 0xBEu };
        static float a[AW * AH * 4], b[AW * AH * 4], c[AW * AH * 4];
        int same = 1, vsame = 1, built = 1;
        for (u32 fi = 0; fi < 2; fi++) for (u32 ri = 0; ri < sizeof remaps / sizeof remaps[0]; ri++) {
            CHECK(vk_eng_depth_store_z24(NULL, big, SW, SH, via_gpu, SW * 4) == 0, "store for alias");
            rsx_tex_layout tl; rsx_texture_layout(fmts[fi], AW, AH, &tl);
            tl.row_bytes = SW * 4;
            static u8 dec[AW * AH * 4];
            rsx_texture_decode(dec, AW * 4, via_gpu, AW, AH, &tl, rsx_texture_argb_is_rgba());
            u32 cpu = vk_eng_texture_create(NULL, RSX_BE_FMT_R8G8B8A8, AW, AH, 1, 1, remaps[ri], fmts[fi]);
            vk_eng_texture_upload(NULL, cpu, 0, 0, AW, AH, dec, AW * 4, AH);
            u32 alias = vk_eng_depth_z24_texture(NULL, AW, AH, remaps[ri], fmts[fi]);
            u32 view = vk_eng_depth_z24_view(NULL, big, AW, AH, remaps[ri], fmts[fi]);
            const u64 t = view ? vk_eng_submit_async(NULL, RSX_BE_FLUSH_GUEST_REFERENCE) : 0;
            built &= cpu && alias && view && t;
            if (cpu && alias && view && t) {
                fetch(cpu, AW, AH, a); fetch(alias, AW, AH, b); fetch(view, AW, AH, c);
                if (memcmp(a, b, sizeof a)) {
                    same = 0;
                    fprintf(stderr, "alias fmt %02X remap %04X: cpu %g %g %g %g gpu %g %g %g %g\n", fmts[fi], remaps[ri],
                            a[0], a[1], a[2], a[3], b[0], b[1], b[2], b[3]);
                }
                if (memcmp(a, c, sizeof a)) {
                    vsame = 0;
                    fprintf(stderr, "view fmt %02X remap %04X: cpu %g %g %g %g gpu %g %g %g %g\n", fmts[fi], remaps[ri],
                            a[0], a[1], a[2], a[3], c[0], c[1], c[2], c[3]);
                }
            }
            if (cpu) vk_eng_release(NULL, cpu);
            if (alias) vk_eng_release(NULL, alias);
            if (view) vk_eng_release(NULL, view);
        }
        CHECK(built, "decoded, alias and view textures built");
        CHECK(same, "alias texels equal the decoded upload's");
        CHECK(vsame, "GPU depth view texels equal the decoded upload's");

        /* Stream order: a clear before the view lands in it, one after does not. */
        {
            u32 o = vk_eng_depth_target_create(NULL, 8, 4), r = vk_eng_depth_target_create(NULL, 8, 4);
            vk_eng_clear_depth_stencil(NULL, o, RSX_BE_CLEAR_DEPTH, 0.25f, 0);
            u32 v = vk_eng_depth_z24_view(NULL, o, 8, 4, 0xAAE4u, 0xA5u);
            CHECK(v && vk_eng_submit_async(NULL, RSX_BE_FLUSH_GUEST_REFERENCE), "ordered view submitted");
            vk_eng_clear_depth_stencil(NULL, o, RSX_BE_CLEAR_DEPTH, 0.75f, 0);
            vk_eng_clear_depth_stencil(NULL, r, RSX_BE_CLEAR_DEPTH, 0.25f, 0);
            u8 tmp[8 * 4 * 4];
            CHECK(vk_eng_depth_store_z24(NULL, r, 8, 4, tmp, 32) == 0, "reference store");
            u32 ref = vk_eng_depth_z24_texture(NULL, 8, 4, 0xAAE4u, 0xA5u);
            float x[8 * 4 * 4], y[8 * 4 * 4];
            if (v && ref) { fetch(v, 8, 4, x); fetch(ref, 8, 4, y); }
            CHECK(v && ref && !memcmp(x, y, sizeof x), "the view holds the depth recorded before it, not the later clear");
            if (v) vk_eng_release(NULL, v);
            if (ref) vk_eng_release(NULL, ref);
            vk_eng_release(NULL, o); vk_eng_release(NULL, r);
        }
        /* A released in-flight view (and its depth) is destroyed only after its
         * ticket retires; buffers come back as spares. */
        {
            u32 zz = vk_eng_depth_target_create(NULL, 4096, 4096);
            const u64 d0 = s_e5.deferred_destroys, r0 = s_e5.view_buffers_reused;
            u32 views[6]; int okv = 1;
            for (u32 i = 0; i < 6; i++) { views[i] = vk_eng_depth_z24_view(NULL, zz, 4096, 4096, 0xAAE4u, 0xA5u); okv &= views[i] != 0; }
            for (u32 i = 0; i < 6; i++) if (views[i]) vk_eng_release(NULL, views[i]);
            vk_eng_release(NULL, zz);
            const u64 deferred = s_e5.deferred_destroys - d0;
            CHECK(okv, "large views built");
            CHECK(vk_eng_submit_and_wait_checked(NULL, RSX_BE_FLUSH_GUEST_REFERENCE) == 1 && s_e5.nretire == 0 &&
                  (!s_bat_on || s_bat.nret == 0), "deferred destroys drain at completion");
            u32 again = vk_eng_depth_target_create(NULL, 64, 64);
            u32 v2 = vk_eng_depth_z24_view(NULL, again, 64, 64, 0xAAE4u, 0xA5u);
            u32 v3 = vk_eng_depth_z24_view(NULL, again, 64, 64, 0xAAE4u, 0xA5u);
            printf("in-flight releases deferred: %llu of 7; view buffers reused so far: %llu\n",
                   (unsigned long long)deferred, (unsigned long long)(s_e5.view_buffers_reused - r0));
            CHECK(v2 && v3, "views after a drain");
            vk_eng_release(NULL, v2); vk_eng_release(NULL, v3); vk_eng_release(NULL, again);
        }
        CHECK(vk_eng_depth_z24_view(NULL, big, SW + 1, SH, 0xAAE4u, 0xA5u) == 0, "view wider than the depth rejected");
        CHECK(vk_eng_depth_z24_view(NULL, big, AW, AH, 0xAAE4u, 0x81u) == 0, "view of other formats rejected");
        CHECK(vk_eng_depth_z24_texture(NULL, SW + 1, SH, 0xAAE4u, 0xA5u) == 0, "alias wider than the store rejected");
        CHECK(vk_eng_depth_z24_texture(NULL, AW, AH, 0xAAE4u, 0x81u) == 0, "alias of other formats rejected");
        vk_eng_release(NULL, big);
        free(fv);
        fetch_shutdown();
    }
    {
        u32 color = vk_eng_color_target_create(NULL, RSX_BE_FMT_R8G8B8A8, 4, 3, NULL, 0);
        u8 guard[16]; memset(guard, 0x5A, sizeof guard);
        CHECK(vk_eng_depth_store_z24(NULL, color, 1, 1, guard, 4) != 0, "colour target rejected");
        CHECK(vk_eng_depth_store_z24(NULL, small, 9, 1, guard, 36) != 0, "wider than the target rejected");
        CHECK(vk_eng_depth_store_z24(NULL, small, 2, 1, guard, 4) != 0, "short pitch rejected");
        CHECK(vk_eng_depth_store_z24(NULL, small, 1, 1, NULL, 4) != 0, "null destination rejected");
        int ok = 1; for (u32 i = 0; i < sizeof guard; i++) ok &= guard[i] == 0x5A;
        CHECK(ok, "rejections leave the destination alone");
        vk_eng_release(NULL, color);
    }
    vk_eng_release(NULL, small); vk_eng_release(NULL, depth);
    CHECK(!vk_e5_failed(), "no submission failed");
    free(bits); free(got);
    printf("%d checks, %d failures GPU=%s\n", checks, failures, props.deviceName);
    rsx_vulkan_backend_shutdown();
    return failures ? 1 : 0;
}
