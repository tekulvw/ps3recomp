/* Vulkan E5 on a real device, headless, under the Khronos validation layer:
 *  - the compute conversion against the engine's CPU D24S8 conversion over
 *    every sampled float bit pattern (all of [0, 1] with DEPTH_Z24_EXHAUSTIVE=1)
 *    and the specials;
 *  - depth_store_z24 against depth_readback + the CPU conversion, padded rows,
 *    a recorded clear landing first, and the rejections;
 *  - depth_z24_texture and depth_z24_view texels against the decoded upload,
 *    for both formats and a spread of crossbars;
 *  - a view holds the depth recorded before it, not a later clear;
 *  - completion tickets: order, a full ring waiting instead of failing, the
 *    checked flush, deferred destruction of a released in-flight view.
 * Runs with per-operation submissions and with PS3RECOMP_VK_BATCHED_ENGINE=1
 * (the runner sets it), where every helper below waits through vk_sync().
 * No window, no guest memory and no game data.
 * python3 tools/test_vulkan_depth_z24.py [--require-hardware ...] */
